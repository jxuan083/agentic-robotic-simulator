"""Validate the numpy FK against PhysX body poses, measure jaw opening, and dump the chain YAML.

Run: docker/isaac/run.sh /isaac-sim/python.sh tools/validate_kinematics.py
Writes outputs/validate_kinematics.txt and configs/so101_chain.yaml
"""

import argparse

from isaaclab.app import AppLauncher

parser = argparse.ArgumentParser()
AppLauncher.add_app_launcher_args(parser)
args = parser.parse_args()
args.headless = True
app = AppLauncher(args).app

import os  # noqa: E402
import sys  # noqa: E402

import numpy as np  # noqa: E402
import torch  # noqa: E402
import yaml  # noqa: E402

import isaaclab.sim as sim_utils  # noqa: E402
from isaaclab.assets import Articulation  # noqa: E402
from pxr import Gf, Usd, UsdGeom, UsdPhysics  # noqa: E402

from agentic_sim.isaac.chain import chain_from_usd, _q  # noqa: E402
from agentic_sim.isaac.so101 import WORKSHOP_COMMIT, so101_cfg  # noqa: E402
from agentic_sim.kinematics import JointDef, MOUNT_FROM_BASE, quat_wxyz_to_mat  # noqa: E402

os.makedirs("outputs", exist_ok=True)
sys.stdout = open("outputs/validate_kinematics.txt", "w", buffering=1)

sim = sim_utils.SimulationContext(sim_utils.SimulationCfg(dt=1 / 120, gravity=(0.0, 0.0, 0.0)))
robot = Articulation(so101_cfg("/World/Robot"))
sim.reset()
stage = sim.stage

chain = chain_from_usd(stage, "/World/Robot", ee_offset=(0.0, 0.0, 0.0))
print("lower", np.round(chain.lower, 4).tolist(), "upper", np.round(chain.upper, 4).tolist())

ids = [robot.joint_names.index(n) for n in ("Rotation", "Pitch", "Elbow", "Wrist_Pitch", "Wrist_Roll")]
gi = robot.body_names.index("gripper")
rng = np.random.default_rng(0)
max_p, max_r = 0.0, 0.0
for k in range(20):
    q5 = rng.uniform(chain.lower * 0.8, chain.upper * 0.8)
    q = robot.data.default_joint_pos.clone()
    q[0, ids] = torch.tensor(q5, dtype=q.dtype, device=q.device)
    robot.write_joint_state_to_sim(q, torch.zeros_like(q))
    robot.set_joint_position_target(q)
    robot.write_data_to_sim()
    sim.step(render=False)
    robot.update(sim.get_physics_dt())
    q_meas = robot.data.joint_pos[0, ids].cpu().numpy()
    p_sim = robot.data.body_pos_w[0, gi].cpu().numpy()
    r_sim = quat_wxyz_to_mat(robot.data.body_quat_w[0, gi].cpu().numpy())
    t = chain.link_poses_base(q_meas)["gripper"]
    dp = np.linalg.norm(t[:3, 3] - p_sim)
    dr = np.degrees(np.arccos(np.clip((np.trace(t[:3, :3].T @ r_sim) - 1) / 2, -1, 1)))
    max_p, max_r = max(max_p, dp), max(max_r, dr)
print(f"FK vs PhysX gripper pose over 20 random configs: max pos err {max_p*1000:.3f} mm, max rot err {max_r:.3f} deg")

# Jaw: which sign opens? measure jaw tip x in gripper frame via jaw joint FK.
jp = UsdPhysics.RevoluteJoint(stage.GetPrimAtPath("/World/Robot/joints/Jaw"))
jaw = JointDef("Jaw", "gripper", "jaw", tuple(jp.GetLocalPos0Attr().Get()), _q(jp.GetLocalRot0Attr().Get()),
               tuple(jp.GetLocalPos1Attr().Get()), _q(jp.GetLocalRot1Attr().Get()), str(jp.GetAxisAttr().Get()))
# authored jaw pose in gripper frame from USD xforms
xc = UsdGeom.XformCache()
g_w = xc.GetLocalToWorldTransform(stage.GetPrimAtPath("/World/Robot/gripper"))
j_w = xc.GetLocalToWorldTransform(stage.GetPrimAtPath("/World/Robot/jaw"))
j_in_g = np.array(j_w * g_w.GetInverse()).T  # Gf matrices are row-major/transposed
# jaw tip inner point measured in gripper frame at authored state
tip_g = np.array([0.0079, 0.0, -0.095, 1.0])
tip_jaw = np.linalg.inv(j_in_g) @ tip_g
for a_deg in (-10, 0, 10, 20, 30, 45, 60, 90, 100):
    t = jaw.transform(np.radians(a_deg))
    p = t @ tip_jaw
    print(f"jaw={a_deg:4d} deg: jaw inner tip in gripper frame x={p[0]:.4f} z={p[2]:.4f}  gap_to_fixed={(p[0]+0.0079)*1000:.1f} mm")
# authored jaw angle estimate
for a_deg in np.arange(-10, 101, 0.5):
    if np.allclose(jaw.transform(np.radians(a_deg)), j_in_g, atol=2e-4):
        print("authored jaw angle approx", a_deg, "deg")
        break

# Mount frame sanity: default pose EE direction
q0 = robot.data.default_joint_pos[0, ids].cpu().numpy()
print("default gripper pose in mount frame:\n", np.round(chain.gripper_pose_mount(q0), 4))
q_zero = np.zeros(5)
print("zero-pose gripper pose in mount frame:\n", np.round(chain.gripper_pose_mount(q_zero), 4))

d = chain.to_dict()
d["source"] = f"Sim-to-Real-SO-101-Workshop@{WORKSHOP_COMMIT} SO-ARM101-USD-NO-CAMERA.usd (generated by tools/validate_kinematics.py)"
os.makedirs("configs", exist_ok=True)
with open("configs/so101_chain.yaml", "w") as f:
    yaml.safe_dump(d, f, sort_keys=False)
print("wrote configs/so101_chain.yaml")
sys.stdout.flush()
os._exit(0)
